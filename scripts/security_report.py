"""Run the test suite and write docs/SECURITY_TEST_REPORT.md from the JUnit
results. Pass/fail/skip status is taken from pytest, never written by hand."""
import json
import platform
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
XML = ROOT / "experiments" / "results" / "pytest-junit.xml"
XML.parent.mkdir(parents=True, exist_ok=True)
subprocess.run([sys.executable, "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={XML}"], cwd=ROOT)

AREA = {
    "S1": "Repeated evaluation requests", "S2": "Duplicate submission and result replay", "S3": "Global budget across participants",
    "S4": "Adaptive / differencing queries", "S5": "Small subgroups", "S6": "Malformed prediction inputs",
    "S7": "Out-of-range labels", "S8": "Missing and unknown item identifiers", "S9": "Oversize payloads",
    "S10": "Concurrent budget consumption", "S11": "Unexpected failures after reservation", "S12": "Restricted disclosure: logs and ledger",
    "S13": "Label-independent failure responses", "S14": "Simulation randomness never used in production",
    "S15": "Ledger unavailable: fail closed",
}
GROUPS = {"test_budget": "D1/D1b: exact privacy-budget accounting", "test_identity": "D2: accounting identity and dataset versions",
          "test_replay": "D3/D4: replay ownership, parameter changes, restart, crash recovery",
          "test_modes": "D8: simulation/production separation, cross-mode replay, restarts",
          "test_host": "H-series and D9: host-side scoring, result gate, dispatch checks, group factor",
          "test_sealed_integration": "S16: real sealed execution (upstream worker, Docker) into the host scorer",
          "test_host_demo_and_fidelity": "Host demonstration and reference-task fidelity reproducibility",
          "test_guarantees": "G-series: ingredients of the formal guarantee (exact privacy loss, sensitivity, coverage, calibration)"}
rows = []
for tc in ET.parse(XML).getroot().iter("testcase"):
    status = "PASS"
    if tc.find("failure") is not None or tc.find("error") is not None:
        status = "FAIL"
    elif tc.find("skipped") is not None:
        status = "UNVERIFIED (" + (tc.find("skipped").get("message") or "skipped") + ")"
    rows.append((tc.get("classname").split(".")[-1], tc.get("name"), status))

counts = {s: sum(1 for r in rows if r[2].startswith(s)) for s in ("PASS", "FAIL", "UNVERIFIED")}
# Machine-readable companion of this report.
(ROOT / "experiments" / "results" / "test-results.json").write_text(json.dumps({
    "python": platform.python_version(), "platform": platform.system(), "counts": counts, "total": len(rows),
    "tests": [{"module": m, "test": n, "result": st} for m, n, st in rows]}, indent=1) + "\n")
sys.path.insert(0, str(ROOT / "src"))
from privatemetrics import ROUTE_VERSION

L = ["# Security test report", "",
     f"**Status: DRAFT — NOT YET APPROVED OR INTEGRATED.** Route version `{ROUTE_VERSION}`.", "",
     "Generated by `scripts/security_report.py` from pytest's JUnit output. Do not edit by hand. "
     f"Executed with Python {platform.python_version()} on {platform.system()}.", "",
     f"**{counts['PASS']} passed, {counts['FAIL']} failed, {counts['UNVERIFIED']} unverified (skipped)** out of {len(rows)} tests.", "",
     "## Scope", "",
     "These tests cover **this component**: host-side scoring, validation, mechanism, post-processing, budget "
     "ledger, adapter. Containment (no network, read-only filesystem, log capture, CPU/memory/process limits, "
     "output-size cap, pull by digest) is **inherited from the upstream reference implementation**. The S16 test "
     "drives the unmodified upstream worker with a real Docker daemon and observes egress blocking, log isolation "
     "and the absence of labels in the container; the remaining caps are covered by the upstream `apps/worker-eval` "
     "suite and are not re-tested here.", "",
     "## Adversarial tests (S-series)", "", "| ID | Area | Test | Result |", "|---|---|---|---|"]
for mod, name, st in rows:
    if mod == "test_security" and name.startswith("test_S"):
        sid = name.split("_")[1].rstrip("abc")
        L.append(f"| {sid} | {AREA.get(sid, '')} | `{name}` | {st} |")
for mod, title in GROUPS.items():
    L += ["", f"## {title} (`tests/{mod}.py`)", "", "| Test | Result |", "|---|---|"]
    L += [f"| `{name}` | {st} |" for m, name, st in rows if m == mod]
L += ["", "## Mechanism, parity, interface and other tests", "", "| Module | Test | Result |", "|---|---|---|"]
for mod, name, st in rows:
    if not (mod == "test_security" and name.startswith("test_S")) and mod not in GROUPS:
        L.append(f"| {mod} | `{name}` | {st} |")
L += ["", "## Negative control (mutation check)", "",
      "`scripts/mutation_check.py` disables one control at a time and checks that the named test then fails. "
      "Rows below are read from `experiments/results/mutation-check.json` as last written by that script; "
      "run it before this one so the two agree.", ""]
MUT = ROOT / "experiments" / "results" / "mutation-check.json"
if MUT.exists():
    L += ["| Mutation | Test expected to fail | Result |", "|---|---|---|"]
    for m in json.loads(MUT.read_text()):
        L.append(f"| {m['mutation']} | `{m['test']}` | {'CAUGHT' if m['caught'] else 'MISSED'} |")
else:
    L.append("NOT EXECUTED: no mutation-check results found.")
L += ["",
      "## Not verified here", "",
      "* Inherited memory, CPU, PID, timeout and output-size caps (see Scope).",
      "* Integration into a host's production worker deployment: NOT IMPLEMENTED (GAP_ANALYSIS G1).",
      "* End-to-end operation with the GI-AI4H platform (dispatch and result POST): NOT EXECUTED.",
      "* Multi-machine shared ledger: NOT IMPLEMENTED (not required per organizer feedback; G7).",
      "* Independent technical and adversarial review (spec §6): NOT STARTED (G19).",
      "* Timing side channels of the scorer: runtime is measured, not shown to be constant; not part of the result.", ""]
(ROOT / "docs" / "SECURITY_TEST_REPORT.md").write_text("\n".join(L) + "\n")
print(f"{counts} -> docs/SECURITY_TEST_REPORT.md")
sys.exit(1 if counts["FAIL"] else 0)
